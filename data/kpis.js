/** The KPIs of a sector, and those of "general" after them. */
export function kpisFor(sector) {
  return KPIS.filter((k) => k.sector === sector).concat(sector === "general" ? [] : KPIS.filter((k) => k.sector === "general"));
}

/** A KPI by its id, or null. */
export function kpiById(id) {
  return KPIS.find((k) => k.id === id) || null;
}
