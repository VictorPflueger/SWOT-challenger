// The sector KPI library (build brief 6.4): the figures the agents measure an issue's impact in, so a
// carrier's issues land in cost per container moved and a utility's in customer churn. Thirteen sectors,
// each with an English and a German name, and 8 to 12 KPIs each (ten in "general", which any company
// can use). A KPI is { id: "<sector>.<name>", sector, name: { en, de }, unit, better, definition:
// { en, de }, source }. Units are symbols, so they read the same in both languages. The library holds
// definitions only, never a benchmark value it cannot source.
//
// The same file in all four tools (brief 4.1); tests/parity.mjs compares it with any sibling checkout
// beside this repository, and tests/kpis.mjs checks its shape.

const CP = "common practice";
